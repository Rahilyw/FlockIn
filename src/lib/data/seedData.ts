/**
 * Function to generate Firestore-ready data with IDs and timestamps
 */
export function generateFirestoreData() {
  const now = new Date();

  const eventsWithIds = seedEvents.map((event, index) => ({
    ...event,
    id: `event_${index + 1}`,
    createdAt: now,
    updatedAt: now,
  }));

  const clubsWithIds = seedClubs.map((club, index) => ({
    ...club,
    id: `club_${index + 1}`,
    createdAt: now,
    updatedAt: now,
  }));

  const resourcesWithIds = seedResources.map((resource, index) => ({
    ...resource,
    id: `resource_${index + 1}`,
    createdAt: now,
    updatedAt: now,
  }));

  return {
    events: eventsWithIds,
    clubs: clubsWithIds,
    resources: resourcesWithIds,
    stats: {
      totalEvents: eventsWithIds.length,
      totalClubs: clubsWithIds.length,
      totalResources: resourcesWithIds.length,
    },
  };
}

export default {
  seedEvents,
  seedClubs,
  seedResources,
  generateFirestoreData,
};
